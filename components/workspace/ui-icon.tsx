function normalizeIconKey(value: string): string {
  return value.trim().toLowerCase().replace(/[\s_-]+/g, "");
}

export function resolveUiIconName(name?: string | null): UiIconName | null {
  if (!name) return null;
  const key = normalizeIconKey(name);
  if (key in ICONS) return key as UiIconName;
  return ALIASES[key] ?? null;
}

const FLIPPED: Partial<Record<UiIconName, boolean>> = {
  back: true,
  prev: true,
  chevronDown: true,
};

export function UiIcon({
  name,
  size = 18,
  className = "",
  color,
}: {
  name: UiIconName;
  size?: number;
  className?: string;
  color?: string;
}) {
  const icon = ICONS[name];
  if (!icon) return null;
  return (
    <HugeiconsIcon
      icon={icon}
      size={size}
      color={color || "currentColor"}
      strokeWidth={1.75}
      className={`${FLIPPED[name] ? "-scale-x-100" : ""} ${name === "chevronDown" ? "rotate-90" : ""} ${className}`}
      aria-hidden="true"
    />
  );
}
